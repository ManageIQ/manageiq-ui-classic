/**
 * Tree helpers — pure functions operating on the flat-map tree format used by
 * the reducers and the window API.
 *
 * Flat-map shape:
 *   { [nodeId: string]: node }
 *   nodeId "" is a root sentinel: { nodeId: "", text: "Root", nodes: [top-level ids] }
 *   every other entry has nodeId as a dot-path string: "0", "0.1", "0.1.2", …
 *   node.nodes is an array of child nodeId strings (not child objects)
 */

// Only falls back when undefined, so that `checked: null` (partial checkbox) is preserved.
const defVal = (value, fallback) => (value === undefined ? fallback : value);

const defaultState = (state = {}) => ({
  checked: defVal(state.checked, false),
  expanded: defVal(state.expanded, false),
  disabled: defVal(state.disabled, false),
  selected: defVal(state.selected, false),
});

/**
 * Recursively stamps nodeId dot-paths onto a hierarchical array and
 * normalises the state object on each node.  Mirrors Tree.initHierarchicalTree.
 */
const initHierarchicalTree = (arr, parentId = '') => arr.map((node, i) => {
  const nodeId = parentId === '' ? String(i) : `${parentId}.${i}`;
  const withId = {
    ...node,
    nodeId,
    state: defaultState(node.state),
  };
  if (withId.nodes) {
    withId.nodes = initHierarchicalTree(withId.nodes, nodeId);
  }
  return withId;
});

/**
 * Flattens a hierarchical (initHierarchicalTree-stamped) array into a
 * { [nodeId]: node } map.  node.nodes becomes an array of child nodeId strings.
 * Adds a root sentinel at key "".  Mirrors Tree.convertHierarchicalTree.
 */
const convertHierarchicalTree = (arr) => {
  const flat = {};
  const stack = [...arr];

  flat[''] = { nodeId: '', text: 'Root', nodes: arr.map((n) => n.nodeId) };

  while (stack.length) {
    const node = stack.pop();
    const childIds = node?.nodes ? node.nodes.map((c) => c.nodeId) : [];
    if (node.nodes) {
      stack.push(...node.nodes);
    }
    flat[node.nodeId] = { ...node, nodes: childIds };
  }

  return flat;
};

/**
 * flatten(data) = convertHierarchicalTree(initHierarchicalTree(data))
 * Direct replacement for the two-step call in the original helpers.js.
 */
const flatten = (data) => convertHierarchicalTree(initHierarchicalTree(data));

/**
 * Normalise a raw bs_tree node array before flattening:
 *   - class => classes
 *   - state.checked "undefined" string => null  (server cannot send null)
 *   - state.checked null => false
 *   - key => attr.key
 */
const normalize = (tree, fn) => tree.map((n) => {
  let node = { ...n };
  if (node.class) {
    node = { ...node, classes: node.class };
    delete node.class;
  }

  if (node.state.checked === 'undefined') {
    node = { ...node, state: { ...node.state, checked: null } };
  } else if (node.state.checked === null) {
    node = { ...node, state: { ...node.state, checked: false } };
  }

  if (node.key) {
    node = { ...node, attr: { key: node.key } };
    delete node.key;
  }

  if (node.nodes) {
    node = { ...node, nodes: normalize(node.nodes, fn) };
  }

  return fn ? fn(node) : node;
});

// This function adjusts the nodes generated by the TreeBuilder for the usage with TreeView
const convert = (data, { check, select } = {}) => flatten(normalize(
  data,
  ({ state: { checked, selected, ...state } = {}, ...node }) => ({
    ...node,
    state: {
      ...state,
      checked: check ? check(node) : checked,
      selected: select ? select(node) : selected,
    },
  }),
));

/**
 * Pure node lookup — replaces Tree.nodeSelector(state, nodeId).
 */
const nodeSelector = (state, nodeId) => state[nodeId];

/**
 * Search all nodes (or descendants of rootNodeId) for nodes where
 * node.attr[attrKey] === attrValue.  Returns an array of matching nodeIds.
 * Replaces Tree.nodeSearch.
 */
const nodeSearch = (state, rootNodeId, attrKey, attrValue) => {
  const candidates = rootNodeId
    ? Object.keys(state).filter((id) => id.startsWith(`${rootNodeId}.`) || id === rootNodeId)
    : Object.keys(state);

  return candidates.reduce((acc, id) => {
    const node = state[id];
    if (node && node.attr && node.attr[attrKey] === attrValue) {
      acc.push(node.nodeId);
    }
    return acc;
  }, []);
};

/**
 * Returns all ancestor nodeIds of a given nodeId, from root down to the
 * immediate parent.  Replaces Tree.getAncestors.
 * e.g. "0.1.2" => ["0", "0.1"]
 */
const getAncestors = (nodeId) => {
  const parts = nodeId.split('.');
  const ancestors = [];
  for (let i = 1; i < parts.length; i += 1) {
    ancestors.push(parts.slice(0, i).join('.'));
  }
  return ancestors;
};

/**
 * Returns all descendant nodeIds of rootNodeId that exist in state.
 * Replaces Tree.getDescendants.
 */
const getDescendants = (state, rootNodeId) => Object.keys(state).filter(
  (id) => id.startsWith(`${rootNodeId}.`),
);

/**
 * Helper
 * Activates the first active node in the tree, which is passed through the props.
 *
 * FIXME Delete this function when backend is sending data where the initial node is activated,
 * or when all the trees calling a reducer if they want to have an activated node at the start.
 */
const activateNode = (tree, doActivate, key) => {
  if (!doActivate) {
    return tree;
  }

  const matchIds = nodeSearch(tree, null, 'key', key);
  let node = nodeSelector(tree, matchIds[0]);
  node = { ...node, state: { ...node.state, selected: true } };
  return { ...tree, [node.nodeId]: node };
};

export {
  // conversion pipeline
  flatten,
  convert,
  // node helpers (used by reducers and window API)
  nodeSelector,
  nodeSearch,
  getAncestors,
  getDescendants,
  // tree-level helpers (used by reducers)
  activateNode,
};
